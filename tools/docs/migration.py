#!/usr/bin/env python3
"""The migration guides (M5), one per language, from one source.

    api/migration.md   -> docs/migrating-to-9/python.md, javascript.md
    api/retired.toml   -> docs/migrating-to-9/python-members.md, javascript-members.md

api/migration.md is written by hand (its source is docs/vnext/deviations.md); its header says how a
paragraph is marked for one language. The members pages list each retired 8.x member in the language
that had it (`lang` in retired.toml), with the 8.x and 9.2 names spelled for that language. A row's
note is kept for the reader, minus the references that only mean something inside this repo
(decision dates, triage ids, generator-log and deviation numbers). docs/migrating-to-9.md (the landing
page) and docs/migrating-to-9/dotnet.md are written by hand.

    python3 tools/docs/migration.py           # write the pages
    python3 tools/docs/migration.py --check   # exit 1 when one is stale
"""
import glob
import json
import os
import re
import sys
import tomllib

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
SOURCE = os.path.join(ROOT, 'api', 'migration.md')
OUT = os.path.join(ROOT, 'docs', 'migrating-to-9')
LANGS = {'py': ('python', 'Python', 'python'), 'js': ('javascript', 'JavaScript', 'js')}   # page, title, fence
HEADER = '<!-- Generated by tools/docs/migration.py from %s. Do not edit. -->\n\n'


# ---- the guides ------------------------------------------------------------------------------

def render(text, lang):
    """api/migration.md for one language"""
    other = 'js' if lang == 'py' else 'py'
    text = text[text.index('\n# ') + 1:]                                     # drop the source's header
    # the other language's blocks (each to its first close) and this language's markers leave a
    # \0; a line that is nothing but those goes with its line break
    text = re.sub(r'<!-- %s -->.*?<!-- /%s -->' % (other, other), '\0', text, flags=re.S)
    text = re.sub(r'<!-- /?%s -->' % lang, '\0', text)
    text = re.sub(r'(?m)^[ \t\0]*\0[ \t\0]*\n', '', text).replace('\0', '')
    text = re.sub(r'(?ms)^( *)```%s\n.*?^\1```\n' % LANGS[other][2], '', text)
    text = re.sub(r'\[\[(.*?)\s+\|\|\s+(.*?)\]\]', lambda m: m.group(1 if lang == 'py' else 2), text, flags=re.S)
    text = re.sub(r'(?m)^[ \t]*-[ \t]*\n', '', text)                        # a bullet left empty
    text = re.sub(r'(?m)[ \t]+$', '', text)
    return re.sub(r'\n{3,}', '\n\n', prune(text)).strip() + '\n'


def prune(text):
    """drop a heading whose section has nothing left but comments and blank lines"""
    lines, out = text.split('\n'), []
    for i, line in enumerate(lines):
        m = re.match(r'^(#+) ', line)
        if m:
            body = []
            for nxt in lines[i + 1:]:
                n = re.match(r'^(#+) ', nxt)
                if n and len(n.group(1)) <= len(m.group(1)):
                    break
                body.append(nxt)
            if not re.sub(r'<!--.*?-->', '', '\n'.join(body), flags=re.S).strip():
                continue
        out.append(line)
    return '\n'.join(out)


# ---- the members pages -----------------------------------------------------------------------

# the old SubD iterator classes had no public name of their own: what a script wrote to get one
OLD_CLASS = {
    'BND_SubDFaceIteratorFromSubD': 'subd.Faces', 'BND_SubDEdgeIteratorFromSubD': 'subd.Edges',
    'BND_SubDVertexIteratorFromSubD': 'subd.Vertices',
    'BND_SubDEdgeIteratorFromVertex': 'vertex.Edges', 'BND_SubDFaceIteratorFromVertex': 'vertex.Faces',
    'BND_SubDEdgeIteratorFromFace': 'face.Edges', 'BND_SubDVertexIteratorFromFace': 'face.Vertices',
    'BND_SubDFaceIteratorFromEdge': 'edge.Faces', 'BND_SubDVertexIteratorFromEdge': 'edge.Vertices',
}

# a note that still talks about the implementation after clean() is left out
INTERNAL = re.compile(r'\b(?:old binding|old one|generated|hand|registry|scoreboard|ON_\w+|ONX_\w+|RHINO_SDK|'
                      r'opennurbs|RDK|native|DecalEnumerator|sibling|Luis|triage|pilot|audit|managed|internal|C\+\+|U\d+)\b', re.I)
# a note written in Python terms, which the JS page leaves out
PYTHONIC = re.compile(r'\b(?:len|list|tuple|dict|isinstance|getattr|None|True|False|self)\b|__\w+__|\[i\]|\bis\b|\b[A-Z]\w*\(')


def clean(note):
    """a retired.toml note, for a reader outside the repo ('' when it is about the implementation)"""
    s, prev = note or '', None
    while s != prev:
        prev, s = s, _clean_once(s)
    s = s.strip(' ;:,-')
    return '' if INTERNAL.search(s) else s.replace('|', '\\|')


def _clean_once(s):
    s = re.sub(r'(?:^|(?<=\s))#\d+(?:\s*\(U\d+\))?\s*:?\s*', '', s)
    s = re.sub(r'\bRH-\d+\s*', '', s)
    s = re.sub(r'^\s*/\s*[A-Z]+\d*\s*:\s*', '', s)
    s = re.sub(r'\btriage [A-Z]+\d*(?:\s*/\s*[A-Z]+\d*)*\s*(?:\([^)]*\))?\s*[:;]?\s*', '', s)
    s = re.sub(r'\baudit\s*:\s*', '', s)
    s = re.sub(r'\s*\(?pilot #\d+\)?[:;]?', '', s)
    s = re.sub(r'\(hand member,?\)', '', s)
    s = re.sub(r'\((?:[^()]|\([^()]*\))*\b(?:Luis|triage)\b(?:[^()]|\([^()]*\))*\)', '', s)
    s = re.sub(r'^\s*(?:triage [A-Z]+\d*\s*(?:\([^)]*\))?|Luis[^:]*):\s*', '', s)
    s = re.sub(r'\s*\((?:[DG]\d+|pilot #\d+)(?:[,;] *(?:[DG]\d+|pilot #\d+))*\)', '', s)
    s = re.sub(r'\b(?:G|D)\d+\b', '', s)
    s = re.sub(r'\s*\(commits;?\)', '', s)
    s = re.sub(r'^JS only\s*[;:,]?\s*', '', s)
    return re.sub(r'\s+([,;:)])', r'\1', re.sub(r'\s{2,}', ' ', s)).strip(' ;,-')


def camel(n):
    return n[:1].lower() + n[1:]


def value_types():
    """the JS value types (plain objects: their constructors are `create`)"""
    out = set()
    for p in glob.glob(os.path.join(ROOT, 'src', 'bindings', '*_gen.cpp')):
        out.update(re.findall(r'value_object<BND_\w+>\("(\w+)Value"\)', open(p).read()))
    return out


def by_name(b, lang, values):
    """a retired.toml `by` entry (Python spelling), for one language's page"""
    cls, m = b.split('.', 1)
    if lang == 'py':
        return {'__init__': cls + '(...)', '__mul__': cls + ' * ' + cls, '__getitem__': cls + '[i]',
                '__iter__': 'for x in ' + cls, '__len__': 'len(%s)' % cls}.get(m, b)
    return {'__init__': 'new %s(...)' % cls,                      # value types too (D92)
            '__mul__': cls + '.multiply', '__getitem__': cls + '.get(i)', '__iter__': 'for...of ' + cls,
            '__len__': cls + '.count'}.get(m, cls + '.' + camel(m))


def rows(lang):
    values = value_types() if lang == 'js' else set()
    out = []
    retired = tomllib.load(open(os.path.join(ROOT, 'api', 'retired.toml'), 'rb'))['retired']
    for x in retired:
        if x.get('lang', lang) != lang:
            continue
        cls = OLD_CLASS.get(x['class'], x['class'].replace('BND_', ''))
        names = x.get('members') or [x['member']]
        if lang == 'js':
            if '.' in cls:
                cls = '%s.%s' % (cls.split('.')[0], camel(cls.split('.')[1]))
            names = [x.get('js') or camel(n) for n in names]
        old = ', '.join('`%s.%s`' % (cls, n) for n in names)
        new = ', '.join('`%s`' % by_name(b, lang, values) for b in x['by']) if x['status'] == 'replaced' else 'removed'
        note = clean(x.get('note'))
        if lang == 'js':
            if x.get('lang') != 'js':
                # a member of an instance in JS spelling (`ann.ParentDimensionStyle` -> parentDimensionStyle);
                # a class's statics and enum values keep their case
                note = '' if PYTHONIC.search(note) else re.sub(r'\b([a-z]\w*)\.([A-Z])', lambda m: m.group(1) + '.' + m.group(2).lower(), note)

        if x['status'] == 'replaced' and sorted('%s.%s' % (cls, n) for n in names) == sorted(by_name(b, lang, values) for b in x['by']):
            # the name is the same in this language: what changed is the signature or the result,
            # unless the member only moved inside RhinoCommon (nothing for a script to change)
            if 'moved out of RhinoCommon' in (x.get('note') or ''):
                continue
            note = note or "same name; RhinoCommon's arguments or result"
        out.append((x['class'].replace('BND_', ''), names[0].lower(), '| %s | %s | %s |' % (old, new, note)))
    if lang == 'js':
        covered = {(x['class'], x.get('js') or camel(n)) for x in retired if x.get('lang', 'js') == 'js'
                   for n in x.get('members') or [x['member']]}
        out += value_rows(covered)
    return [r for *_, r in sorted(out)]


def dts_value_types():
    """the 9.2 JS value types from the committed typings: {type: (fields, {static: params})}"""
    d = open(os.path.join(ROOT, 'src', 'js', 'rhino3dm.d.ts')).read()
    out = {}
    for t, body in re.findall(r'\n\tinterface (\w+) \{(.*?)\n\t\}', d, re.S):
        cls = re.search(r'\n\tclass %s \{(.*?)\n\t\}' % t, d, re.S)
        if not cls:
            continue
        st = {}
        for n, ps in re.findall(r'\n\t\tstatic (?:readonly )?(\w+)(?:\(([^)]*)\))?', cls.group(1)):
            st.setdefault(n, [p.split(':')[0].strip('? ') for p in ps.split(',') if p.strip()])
        out[t] = (re.findall(r'\n\t\t(\w+)\??:', body), st)
    return out


def value_rows(covered):
    """the JS members page's rows for the 8.x members of the classes 9.2 makes plain value objects
    (api/js8-value-members.json): `arc.circumference` is `rhino.Arc.circumference(arc)`, `arc.radius`
    is the field `arc.Radius`. Every 8.x member must map, or have its own row in retired.toml"""
    old = json.load(open(os.path.join(ROOT, 'api', 'js8-value-members.json')))
    now = dts_value_types()
    out, missing = [], []
    for t, members in old.items():
        if not t[0].isupper():
            continue
        fields, st = now[t]
        var = camel(t)
        for m in members:
            static = m.startswith('static:')
            n = m[len('static:'):] if static else m
            if (t, n) in covered:
                continue
            if static:
                if n in st:
                    continue                                   # the same static
                missing.append('%s.%s' % (t, m))
                continue
            fn = n if n in st else n[:1].upper() + n[1:] if n[:1].upper() + n[1:] in st else None
            if fn is not None:
                ps = st[fn]
                if not ps or ps[0] != var:
                    missing.append('%s.%s' % (t, m))               # a static that is not the method
                    continue
                new, note = 'rhino.%s.%s(%s)' % (t, fn, ', '.join(ps)), ''
            elif n.lower() in {f.lower() for f in fields}:
                f = [f for f in fields if f.lower() == n.lower()][0]
                new, note = '%s.%s' % (var, f), 'a field of the plain object'
            else:
                missing.append('%s.%s' % (t, m))
                continue
            out.append((t, n.lower(), '| `%s.%s` | `%s` | %s |' % (t, n, new, note)))
    if missing:
        raise SystemExit('api/js8-value-members.json: no 9.2 counterpart and no retired.toml row: %s'
                         % ', '.join(missing))
    return out


def members_page(lang):
    page, title, _ = LANGS[lang]
    other = 'JavaScript' if lang == 'py' else 'Python'
    return (HEADER % 'api/retired.toml' +
            '# Renamed and removed members (%s)\n\n[← Migrating to rhino3dm 9.2 (%s)](%s.md)\n\n' % (title, title, page) +
            '<!-- D19 -->\nThe 8.x %s members that 9.2 replaces with RhinoCommon\'s, or removes. Members rhino3dm keeps\n'
            'alongside RhinoCommon\'s API are not listed, nor are members only 8.x %s had. Search this\n'
            'page for the name your script uses.\n\n' % (title, other) +
            '| rhino3dm 8.x | 9.2 | Note |\n|---|---|---|\n' + '\n'.join(rows(lang)) + '\n')


# ----------------------------------------------------------------------------------------------

def pages():
    src = open(SOURCE).read()
    out = {}
    for lang, (page, _, _) in LANGS.items():
        out[page + '.md'] = HEADER % 'api/migration.md' + render(src, lang)
        out[page + '-members.md'] = members_page(lang)
    return out


def unknown_tests():
    """retired.toml `test` names no test in tests/python or tests/javascript defines (G151: the
    tests/generated fold renamed them all, and nothing noticed)"""
    names = set()
    for p in glob.glob(os.path.join(ROOT, 'tests', 'python', '*.py')):
        names.update(re.findall(r'\bdef (test_\w+)', open(p).read()))
    for p in glob.glob(os.path.join(ROOT, 'tests', 'javascript', '*.js')):
        names.update(re.findall(r"\btest\('(\w+)'", open(p).read()))
    rows = tomllib.load(open(os.path.join(ROOT, 'api', 'retired.toml'), 'rb'))['retired']
    return sorted({x['test'] for x in rows if x.get('test') and x['test'] not in names})


def main():
    stale = []
    missing = unknown_tests()
    if missing:
        print('api/retired.toml names tests that do not exist: %s' % ', '.join(missing))
        if '--check' in sys.argv:
            sys.exit(1)
    for name, text in pages().items():
        path = os.path.join(OUT, name)
        if not os.path.exists(path) or open(path).read() != text:
            stale.append(name)
            if '--check' not in sys.argv:
                open(path, 'w').write(text)
    if '--check' in sys.argv:
        if stale:
            print('stale: %s (python3 tools/docs/migration.py)' % ', '.join(stale))
        sys.exit(1 if stale else 0)
    for name, text in pages().items():
        print('docs/migrating-to-9/%s: %d lines' % (name, text.count('\n')))


if __name__ == '__main__':
    main()
