"""The generated binding surface, as a committed lock (api/generated-surface.lock).

One line per registration the generated code makes -- what a Python or JS
user can call -- parsed from the generated sources themselves (so value
types, dispatchers and bridges are covered alike):

    py  CurveX.PointAt(t)                      method / static / property
    py  CurveX.Domain [property rw]
    py  PlaneSurfaceX.__init__(BND_PlaneX, BND_IntervalX, BND_IntervalX)
    js  CurveX.pointAt [function]

A regeneration that ADDS lines updates the lock. One that REMOVES or CHANGES
a line fails, listing them, unless RH3DM_ACCEPT=1 -- a member silently
disappearing (an ordering bug in the planner, a manifest change) is the
regression this exists to catch.
"""

import os
import re

PY_CLASS = re.compile(r'py::class_<[^>]*>\(m, "(\w+)"')
# `class_<BND_SurfaceX, base<BND_GeometryBaseX>>("SurfaceX")`: the template
# arguments nest, so match lazily up to `>("` (`[^>]*` missed every derived class)
JS_CLASS = re.compile(r'\bclass_<.*?>\("(\w+)"\)')
PY_DEF = re.compile(r'\.(def|def_static|def_property|def_property_readonly|def_property_readonly_static)\("(\w+)"(.*)')
# `py::init<const std::vector<BND_Point3dX>&>()`: template arguments nest (G82)
PY_INIT = re.compile(r'\.def\(py::init<(.*?)>\(\)')
JS_DEF = re.compile(r'\.(function|class_function|property)\("(\w+)"')
JS_CTOR = re.compile(r'\.constructor(<.*?>)?\(')


def surface(files):
    """{(lang, line)} for every registration in the generated files"""
    out = set()
    for name, text in files.items():
        if not name.endswith('.cpp'):
            continue
        py_cls = js_cls = None
        for raw in text.split('\n'):
            line = raw.strip()
            m = PY_CLASS.search(line)
            if m:
                py_cls = m.group(1)
            m = JS_CLASS.search(line)
            if m and 'py::' not in line:
                js_cls = m.group(1)
            if line.startswith('.def') and py_cls:
                mi = PY_INIT.search(line)
                if mi:
                    out.add('py  %s.__init__(%s)' % (py_cls, mi.group(1)))
                    continue
                md = PY_DEF.match(line)
                if md:
                    kind, member, rest = md.groups()
                    if kind.startswith('def_property'):
                        rw = 'rw' if kind == 'def_property' else 'ro'
                        out.add('py  %s.%s [property %s%s]'
                                % (py_cls, member, rw, ' static' if kind.endswith('static') else ''))
                    else:
                        args = re.findall(r'py::arg\("(\w+)"\)', rest)
                        out.add('py  %s.%s(%s)%s' % (py_cls, member, ', '.join(args),
                                                     ' [static]' if kind == 'def_static' else ''))
            elif js_cls and line.startswith('.'):
                md = JS_DEF.match(line)
                if md:
                    out.add('js  %s.%s [%s]' % (js_cls, md.group(2), md.group(1)))
                elif JS_CTOR.match(line):
                    ctor = JS_CTOR.match(line).group(1)
                    out.add('js  %s.constructor%s' % (js_cls, ctor or '(dispatched)'))
    return out


def check(files, lock_path, dry_run):
    """compare with the lock; returns (ok, removed, added). Writes the lock
    when nothing was removed (or RH3DM_ACCEPT=1), unless this is a dry run."""
    now = surface(files)
    before = set()
    if os.path.exists(lock_path):
        before = {l for l in open(lock_path, encoding='utf-8').read().split('\n')
                  if l and not l.startswith('#')}
    removed, added = sorted(before - now), sorted(now - before)
    accept = os.environ.get('RH3DM_ACCEPT') == '1'
    ok = not removed or accept
    if ok and not dry_run and (removed or added or not os.path.exists(lock_path)):
        with open(lock_path, 'w', encoding='utf-8', newline='\n') as f:
            f.write('# GENERATED by tools/generate/bnd_gen.py: the generated binding surface.\n'
                    '# A regeneration that removes or changes a line fails unless\n'
                    '# RH3DM_ACCEPT=1 (see tools/generate/surface_lock.py).\n')
            f.write('\n'.join(sorted(now)) + '\n')
    return ok, removed, added
