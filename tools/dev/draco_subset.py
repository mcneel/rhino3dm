"""Write src/draco_sources.cmake: the Draco sources rhino3dm compiles.

rhino3dm (and RhinoCommon's c/draco.cpp, synced into librhino3dm_native) uses only Draco's mesh and
point-cloud encoder/decoder. A decoder must read anything an encoder writes, so every compression
scheme is in; Draco's file readers (io/), animation, scene, the glTF transcoder (material/, texture/
behind DRACO_TRANSCODER_SUPPORTED, off), tools, wrappers and third_party are not. The set is the
include closure of the headers draco.cpp includes, plus each reached header's .cc. Rerun after
updating the src/lib/draco submodule:

    python3 tools/dev/draco_subset.py
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'src', 'lib', 'draco', 'src')
ROOTS = ['draco/mesh/mesh.h', 'draco/compression/encode.h', 'draco/compression/decode.h',
         'draco/core/encoder_buffer.h', 'draco/core/decoder_buffer.h']
SKIP_DIRS = ('draco/material/', 'draco/texture/', 'draco/io/', 'draco/scene/', 'draco/animation/',
             'draco/tools/', 'draco/javascript/', 'draco/maya/', 'draco/unity/')
INCLUDE = re.compile(r'#include\s+"(draco/[^"]+)"')


def closure():
    seen, todo = set(), list(ROOTS)
    while todo:
        f = todo.pop()
        if f in seen or f.startswith(SKIP_DIRS) or not os.path.exists(os.path.join(SRC, f)):
            continue
        seen.add(f)
        todo.extend(INCLUDE.findall(open(os.path.join(SRC, f), errors='replace').read()))
        if f.endswith('.h') and os.path.exists(os.path.join(SRC, f[:-2] + '.cc')):
            todo.append(f[:-2] + '.cc')
    return sorted(x for x in seen if x.endswith('.cc'))


def main():
    cc = closure()
    out = os.path.join(ROOT, 'src', 'draco_sources.cmake')
    with open(out, 'w', newline='\n') as f:
        f.write('# GENERATED by tools/dev/draco_subset.py -- DO NOT EDIT.\n'
                '# The Draco encode/decode subset rhino3dm compiles (%d sources) instead of\n'
                '# add_subdirectory(lib/draco), with lib/draco_config providing draco_features.h.\n'
                'set(draco_subset_DIR "${CMAKE_CURRENT_LIST_DIR}/lib/draco/src")\n'
                'set(draco_subset_INCLUDE "${CMAKE_CURRENT_LIST_DIR}/lib/draco/src" "${CMAKE_CURRENT_LIST_DIR}/lib/draco_config")\n'
                'set(draco_subset_SRC\n' % len(cc))
        for c in cc:
            f.write('  "${draco_subset_DIR}/%s"\n' % c)
        f.write(')\n')
    print('%s: %d sources' % (os.path.relpath(out, ROOT), len(cc)))


if __name__ == '__main__':
    main()
